import type { Translator, TranslationValues } from './translator';

// ============================================================
// «Ключ вместо слова» в вечном payload.
//
// Уведомление и запись хроники живут в БД годами и хранят СТРУКТУРУ, а текст
// собирается при чтении в языке зрителя (render-at-read, docs/i18n.md). Но часть
// плейсхолдеров фразы — это не данные, а СЛОВА продукта: вид кадрового действия,
// способ вручения, подпись изменённого поля. Записанные словом, они застыли бы в
// языке того, кто нажал кнопку, и английский читатель получил бы русский кусок
// внутри английской фразы.
//
// Поэтому продюсер кладёт в payload не слово, а КЛЮЧ каталога под именем с
// суффиксом `Key`:
//
//   payload: { kindLabelKey: 'hr.actionKind.transfer', docCount: 2 }
//   каталог: "{actorName} завёл действие «{kindLabel}»{documentSuffix}"
//
// Рендер подставляет перевод под именем БЕЗ суффикса. Сам ключ остаётся в
// значениях — по нему видно происхождение слова, и старые записи со снимком
// слова (`kindLabel`) продолжают читаться как есть.
//
// Ключ переводится ТЕМИ ЖЕ значениями, что и внешняя фраза, поэтому подстановка
// может считать: `" (документов: {docCount})"`. Неизвестный каталогу ключ
// игнорируется — фраза не рассыпается из-за типа, чей словарь ещё не переехал.
// ============================================================

const SUFFIX = 'Key';

/**
 * Развернуть `<имя>Key` в `<имя>` переводом из каталога. Возвращает НОВЫЙ объект;
 * уже заданное `<имя>` (снимок старой записи) не перебивается.
 */
export function resolveLabelKeys(t: Translator, values: TranslationValues): TranslationValues {
  let out: TranslationValues | null = null;
  for (const [name, value] of Object.entries(values)) {
    if (!name.endsWith(SUFFIX) || name.length === SUFFIX.length) continue;
    if (typeof value !== 'string' || !t.has(value)) continue;
    const target = name.slice(0, -SUFFIX.length);
    if (values[target] !== undefined) continue;
    out ??= { ...values };
    // Значения берём из УЖЕ накопленного объекта: подстановка может опираться на
    // имя, развёрнутое соседним ключом выше по payload (способ вручения → фраза
    // «{methodName} — «{title}»»). Порядок — порядок ключей payload.
    out[target] = t(value, out);
  }
  return out ?? values;
}
