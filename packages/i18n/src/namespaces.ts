/**
 * Неймспейс = сервис или движок. Один неймспейс — один файл на локаль
 * (`messages/<locale>/<namespace>.json`).
 *
 * Правило страницы: серверный layout сервиса кладёт в клиентский провайдер
 * ТОЛЬКО свои неймспейсы + общие (`common`, `shell`) — иначе каждая страница
 * тащила бы на клиент каталог всей платформы.
 *
 * Добавление неймспейса = строка здесь + три файла (en/kk/ru). Страж
 * `pnpm check:i18n` не даст забыть ни одно из четырёх действий.
 */
export const NAMESPACES = [
  /** Слова, у которых нет одного хозяина: «Отмена», «Сохранить», дни, единицы */
  'common',
  /** Каркас приложения: меню сервисов, шапка, сайдбар, переключатель организации */
  'shell',
  /** Вход, регистрация, восстановление пароля, гостевые страницы */
  'auth',
  /** Публичная витрина `/`: первый экран человека, ещё не выбравшего язык */
  'landing',
  /** Профиль и настройки (включая секцию «Язык и регион») */
  'profile',
  /** Тексты отказов API (`errors.<code>`) — рендерятся сервером в языке запроса */
  'errors',
  /** Заголовки и тела уведомлений (`<type>.title` / `<type>.body`) */
  'notifications',
  /** Хроника: шаблоны записей (`type.<typeKey>`) и подписи полей (`fields.…`) */
  'chatter',
  /** Мессенджер: системные плашки и подписи ленты */
  'messenger',
  /** Общие подписи рич-карт (типы сущностей, действия) */
  'richCards',
] as const;

export type Namespace = (typeof NAMESPACES)[number];

/** Неймспейсы, которые нужны каждой странице (провайдер layout'а всегда их добавляет). */
export const CORE_NAMESPACES: readonly Namespace[] = ['common', 'shell'];

export function isNamespace(value: unknown): value is Namespace {
  return typeof value === 'string' && (NAMESPACES as readonly string[]).includes(value);
}
