export type Namespace = (typeof NAMESPACES)[number];

/** Неймспейсы, которые нужны каждой странице (провайдер layout'а всегда их добавляет). */
export const CORE_NAMESPACES: readonly Namespace[] = ['common', 'shell'];

export function isNamespace(value: unknown): value is Namespace {
  return typeof value === 'string' && (NAMESPACES as readonly string[]).includes(value);
}
