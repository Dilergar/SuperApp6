// ============================================================
// Мультиязычность — константы ПРОВОДА (без каталогов сообщений).
//
// Здесь живёт только то, что обязано совпадать на ОБЕИХ сторонах провода:
// перечень локалей, язык-источник, язык по умолчанию и имя cookie. Слова
// (каталоги ICU-сообщений) живут в отдельном пакете `@superapp/i18n` — его
// тянут API и веб, но не тянет мобильный контракт типов.
//
// Модель Apple/Salesforce: «язык интерфейса» и «региональный профиль форматов» —
// РАЗНЫЕ понятия. Здесь только язык (`uiLocale`); форматы дат/чисел/валюты
// казахстанские при любом языке (профиль региона — в `@superapp/i18n/config`).
// ============================================================

/**
 * Языки интерфейса. BCP-47; порядок здесь — КАНОНИЧЕСКИЙ (алфавит по коду): он
 * задаёт обход в стражах и генераторах, где важна только повторяемость.
 * Порядок ПОКАЗА — отдельный (`LOCALE_DISPLAY_ORDER`).
 */
export const SUPPORTED_LOCALES = ['en', 'kk', 'ru'] as const;

export type Locale = (typeof SUPPORTED_LOCALES)[number];

/**
 * Язык НАПИСАНИЯ (модель Google/Apple): новые фразы пишутся по-английски
 * первыми, ru и kk — переводы. Он же единственный запасной язык: страж
 * `check:i18n` требует 100 % паритета ключей, поэтому фолбэк реально работает
 * только для будущих языков, которые ещё переводятся.
 */
export const SOURCE_LOCALE: Locale = 'en';

/**
 * Язык гостя, чей браузер не назвал НИ ОДНОГО знакомого языка (немецкий,
 * турецкий, вообще без заголовка). Английский — потому что это единственный
 * язык, который такой человек с наибольшей вероятностью прочитает; казахский
 * или русский были бы для него такой же загадкой, как его язык для нас.
 *
 * Не путать с языком РЫНКА (`RegionProfile.defaultLocale` = kk): тот отвечает на
 * другой вопрос — «на каком языке говорит страна, для которой сделан продукт».
 */
export const DEFAULT_LOCALE: Locale = 'en';

/**
 * Cookie с выбранным языком. Адрес страницы языка НЕ несёт (модель
 * Gmail/Salesforce): deep-links и хелперы адресов остаются как есть, а язык
 * едет cookie + `User.locale`.
 */
export const LOCALE_COOKIE = 'sa6_locale';

/**
 * Заголовок ЯВНОГО выбора языка. Отдельный от `Accept-Language` намеренно:
 * `Accept-Language` — это ПОДСКАЗКА БРАУЗЕРА («какие языки я понимаю»), и
 * продукт вправе её маршрутизировать (русскоязычный гость в Казахстане видит
 * государственный язык). А выбор, сделанный руками в переключателе, — это
 * решение человека, и никакой маршрут его перебивать не смеет. Пока оба ехали
 * одним заголовком, сервер не мог их различить.
 */
export const LOCALE_HEADER = 'X-Locale';

/** Год: язык — долгоживущий выбор, а не сессионный. */
export const LOCALE_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

/**
 * Автонимы — ЕДИНСТВЕННЫЕ строки продукта, которые не переводятся: язык в
 * переключателе всегда назван на самом себе (иначе человек, попавший в чужой
 * язык, не найдёт свой).
 */
export const LOCALE_NAMES: Record<Locale, string> = {
  en: 'English',
  kk: 'Қазақша',
  ru: 'Русский',
};

/**
 * Порядок в переключателе. НЕ алфавитный и не по коду — продуктовый:
 * государственный язык страны первым, международный вторым, остальные дальше.
 * Алфавит по автониму давал «Қазақша, Русский, English» — то есть ставил язык
 * соседней страны выше международного, хотя выбор между ними делают чаще.
 *
 * Тот же порядок обязан быть у mobile — поэтому список здесь, в пакете провода,
 * а не в компоненте веба.
 */
export const LOCALE_DISPLAY_ORDER: readonly Locale[] = ['kk', 'en', 'ru'];

/** Строка — одна из поддерживаемых локалей? (нарратив прост, но нужен трижды) */
export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}
