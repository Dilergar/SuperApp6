/** Состояние ссылки — вычисляемое, в базе не хранится (иначе его пришлось бы догонять кроном) */
export const SHARE_LINK_STATUSES = ['active', 'revoked', 'expired', 'exhausted'] as const;
export type ShareLinkStatus = (typeof SHARE_LINK_STATUSES)[number];

/**
 * Единственное место, где решается «жива ли ссылка»: сервер считает статус для
 * DTO, веб — подпись чипа. Порядок веток важен: отзыв сильнее срока, срок
 * сильнее лимита — человек должен видеть первопричину, а не последствие.
 */
export function shareLinkStatus(link: {
  revokedAt: Date | string | null;
  expiresAt: Date | string | null;
  maxOpens: number | null;
  openCount: number;
}): ShareLinkStatus {
  if (link.revokedAt) return 'revoked';
  if (link.expiresAt && new Date(link.expiresAt).getTime() <= Date.now()) return 'expired';
  if (link.maxOpens !== null && link.openCount >= link.maxOpens) return 'exhausted';
  return 'active';
}

