// ============================================================
// Шаблоны документов (core/templates) — СИНТАКСИС и справочники.
//
// Синтаксис — НАШ, драйвер рендера — сменная деталь (решение Этапа 3
// проекта «Документы»): шаблоны клиентов написаны на этом синтаксисе,
// и смена драйвера их не трогает.
//
//   {Organization.Bin}              — поле из группы реестра
//   {Employee.FullName|words}       — форматтеры цепочкой через |
//   {Document.Date|date:long}       — аргумент форматтера после :
//   {#Rows} … {/Rows}               — повтор СТРОКИ ТАБЛИЦЫ по коллекции
//   {No}                            — номер элемента внутри повтора (с 1)
//
// Внутри повтора поля элемента пишутся БЕЗ префикса ({Title}), номер —
// {No}; поля групп ({Organization.…}) продолжают работать.
//
// Имена — английские: тег это API-имя поля (модель Salesforce), одно на все
// языки бланка. Подпись и пояснение к нему живут в каталоге.
// ============================================================

/**
 * Имена форматтеров — то, что сотрудник пишет после `|` в теге. Имя же служит
 * ключом каталога: подпись и пояснение — `documents.formatter.<name>.*`.
 */
export const TEMPLATE_FORMATTERS = ['date', 'words', 'number'] as const;

export type TemplateFormatterKey = (typeof TEMPLATE_FORMATTERS)[number];

/** Аргументированные варианты форматтеров (для валидации компилятором) */
export const TEMPLATE_FORMATTER_ARGS: Record<string, readonly string[]> = {
  date: ['long'],
  words: ['number'],
  number: [],
};

export const TEMPLATE_LIMITS = {
  /** Потолок размера шаблона .docx на рендер (байты) */
  maxTemplateBytes: 20 * 1024 * 1024,
  /** Потолок элементов одного повтора — стоп-кран от случайного миллиона строк */
  maxRepeatItems: 500,
  /** Потолок длины подставляемого значения (символы) */
  maxValueLength: 20_000,
} as const;

/**
 * Тег номера элемента внутри повтора. Не «#»: с решётки начинается открытие
 * повтора (`{#Rows}`), и `{#}` читался бы как повтор без имени коллекции.
 */
export const TEMPLATE_INDEX_TAG = 'No';
