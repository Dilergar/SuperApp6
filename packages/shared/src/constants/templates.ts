//   {Документ.Дата|дата:долгая}     — аргумент форматтера после :
//   {#Строки} … {/Строки}           — повтор СТРОКИ ТАБЛИЦЫ по коллекции
//   {№}                              — номер элемента внутри повтора (с 1)
//
// Внутри повтора поля элемента пишутся БЕЗ префикса ({Название}), номер —
// {№}; поля групп ({Организация.…}) продолжают работать.
// ============================================================

