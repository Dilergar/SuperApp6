/**
 * Уровень движка → `ApprovalDecision.signatureKind`.
 *
 * Существующий enum approvals `['internal','sms','ecp']` НЕ переименовываем:
 * решения уже записаны, а история решений неизменяема. `pep` ложится в `sms`.
 */
export function approvalSignatureKindOf(level: SignLevel): 'sms' | 'ecp' {
  return level === 'ecp' ? 'ecp' : 'sms';
}

/** Обратное соответствие: чего требует шаг маршрута → какой уровень его закроет */
export function signLevelOfRequirement(kind: 'sms' | 'ecp'): SignLevel {
  return kind === 'ecp' ? 'ecp' : 'pep';
}

