// ============================================================
// Соглашение сторон и согласия — версионируемые тексты
// ============================================================
//
// ПЭП равнозначна собственноручной подписи не сама по себе, а ПО СОГЛАШЕНИЮ
// СТОРОН (ст. 47 ЦК, ст. 152 ГК РК). Поэтому текст соглашения:
//   1) показывается ДО ввода кода,
//   2) снимается СНИМКОМ в акт (`consentText`) вместе с версией,
//   3) отдельным событием `consent` попадает в append-only протокол.
//
// Версия обязательна: текст со временем меняется, а доказывать придётся тот,
// который человек видел. Живая ссылка на «текущую редакцию» доказательством не
// является — поэтому в акт едет сам текст, а не его адрес.

/**
 * Редакция текстов согласий. Версия обязана меняться вместе с ТЕКСТОМ — в том
 * числе когда текст переведён на другой язык: доказывать придётся ту редакцию,
 * которую человек видел.
 */
export const SIGN_CONSENT_VERSION = '2026-09-1';

/**
 * Тексты согласий живут в каталоге `sign.consent.*`, а собирает их API
 * (`SignConsentService`) в языке ЗАПРОСА подписанта: человек соглашается с тем,
 * что прочитал, поэтому в акт снимается ровно та строка, которую ему показали.
 *
 *   `sign.consent.pep`            соглашение сторон о ПЭП (ст. 46–47 ЦК, ст. 152 ГК)
 *   `sign.consent.pd`             согласие на обработку ПД (ст. 8 закона о ПД)
 *   `sign.consent.orgSuffix`      « (Организация)» — когда владелец известен
 *   `sign.consent.pdHolderOrg`    получатель согласия: организация
 *   `sign.consent.pdHolderOwner`  получатель согласия: владелец документа
 */

/**
 * Путь публичной страницы проверки подписи (ст. 61 ЦК — открытый сервис проверки).
 * Строкой на месте не собирать: адрес печатается в QR на протоколе подписания и
 * уходит в экспортный пакет, то есть живёт на бумаге у третьих лиц.
 */
export const SIGN_CHECK_PATH = '/check';

export function signCheckUrl(webUrl: string, actId: string, checkToken: string): string {
  return `${webUrl.replace(/\/+$/, '')}${SIGN_CHECK_PATH}/${actId}?k=${checkToken}`;
}

/** Адрес карточки подписания внутри приложения (для уведомлений и стопки) */
export function signRequestHref(requestId: string, workspaceId?: string | null): string {
  return workspaceId ? `/workspaces/${workspaceId}/sign/${requestId}` : `/sign/${requestId}`;
}

/**
 * Маскировка ИИН для посторонних глаз: публичная страница проверки обязана
 * показывать, ЧЕЙ ключ подписал, но выкладывать ИИН целиком в открытый доступ —
 * это раздача персональных данных всякому, кто получил файл.
 */
export function maskIin(iin: string | null | undefined): string | null {
  if (!iin) return null;
  const s = iin.trim();
  if (s.length < 6) return '•'.repeat(s.length);
  return `${s.slice(0, 2)}${'•'.repeat(s.length - 6)}${s.slice(-4)}`;
}

