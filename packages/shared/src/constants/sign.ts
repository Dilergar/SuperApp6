// ============================================================
// Движок электронной подписи (core/sign, 15-й платформенный) — константы
// ============================================================
// Шаг 3 документной вертикали: «Диск → шаблоны → ПОДПИСЬ → ЭДО → КЭДО».
// До него подпись в платформе была `signatureKind='internal'` — нажатие кнопки
// в «Ждут решения», юридической силы ноль.
//
// Юридическая рамка — Цифровой кодекс РК № 255-VIII (действует с 12.07.2026;
// прежний закон об ЭЦП № 370-II утратил силу). Два уровня, и путать их нельзя:
//
//   ЭЦП (квалифицированная, ст. 49 ЦК) — ключ НУЦ РК, полученный по QR eGov
//   Mobile либо через NCALayer. Обязательна для кадровых документов (ст. 33 ТК
//   РК), ЭСФ и обращений в госорганы. Достаточна везде.
//
//   ПЭП («цифровое подтверждение», ст. 46 п. 4 + ст. 47 ЦК) — SMS-код после
//   цифровой аутентификации. Достаточна для гражданско-правовых отношений
//   ПО СОГЛАШЕНИЮ СТОРОН, поэтому текст соглашения снимается в акт (см.
//   SIGN_CONSENT ниже) — без него подпись не соответствует норме.
//
// Движок НЕ содержит маршрута: маршрут — это core/approvals (шаг `signature`)
// и Процессы. Его дело — акт подписи, криптография и её проверка, ВЕЧНЫЕ
// доказательства, экспорт и публичная проверка (ст. 61 ЦК).

/**
 * Способ подписания.
 *
 * `qr` — eGov Mobile: человек сканирует QR, ключ лежит в облаке НУЦ (ст. 51 ЦК
 *   легализовала облачное хранение закрытых ключей), подпись возвращается нам
 *   мостом Smart Bridge. Уровень — полноценная ЭЦП, а не «упрощённая».
 * `ncalayer` — настольный NCALayer: ключ в файле/на токене у человека, CMS
 *   собирается ЦЕЛИКОМ в браузере (WebSocket wss://127.0.0.1:13579), сервер
 *   получает готовый контейнер и проверяет его верификатором.
 * `pep_otp` — ПЭП: согласие сторон + SMS-код ПОД КОНКРЕТНЫЙ документ.
 *
 * Биометрия — осознанный слот на будущее и в v1 не реализована: свою биометрию
 * мы не обрабатываем (ст. 48 ЦК), Face ID остаётся внутри eGov Mobile.
 */
export const SIGN_METHODS = ['qr', 'ncalayer', 'pep_otp'] as const;
export type SignMethod = (typeof SIGN_METHODS)[number];

