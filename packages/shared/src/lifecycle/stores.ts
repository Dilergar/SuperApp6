// ================= Семейства ключей Redis =================
interface RedisFamilyDef {
  patterns: readonly string[];
  role: LifecycleRedisRole;
  maxTtlSeconds: number | null;
  owner: string;
  dataClass: LifecycleDataClass;
  /** Шаблон ключей одного человека: стирание субъекта = DEL (+ BGREWRITEAOF по расписанию) */
  subjectPattern?: string;
  reason: string;
}

function redis(family: string, d: RedisFamilyDef): LifecyclePolicyInput {
  const store: LifecycleStore = {
    kind: 'redis',
    family,
    patterns: d.patterns,
    role: d.role,
    maxTtlSeconds: d.maxTtlSeconds,
    ...(d.subjectPattern ? { subjectPattern: d.subjectPattern } : {}),
  };
  return {
    store,
    owner: d.owner,
    version: 1,
    dataClass: d.dataClass,
    ownerKey: global(d.reason),
    subjects: d.subjectPattern ? [subject('key', 'owner')] : [],
    legalBasis: interest(d.reason),
    retention: d.maxTtlSeconds === null ? keep() : forDays(Math.max(1, Math.ceil(d.maxTtlSeconds / 86_400))),
    onSubjectErasure: d.subjectPattern ? ERASE_REDIS : noSubject('keys carry no personal data (ids, counters, hashes)'),
    onTenantPurge: NOT_TENANT,
    edges: [],
    enforcement: d.maxTtlSeconds === null ? notEnforced('bounded by MAXLEN / single key, not by time') : TTL,
    holdAware: false,
  };
}

