/** Байты живут, пока жива строка FileObject (и её последнее место — FileLink): срок у файла, не у профиля. */
function blob(profile: string, dataClass: LifecycleDataClass, extra: Partial<LifecyclePolicyInput> = {}): LifecyclePolicyInput {
  return {
    store: { kind: 'blob', profile },
    owner: 'core/files',
    version: 1,
    dataClass,
    ownerKey: via('user', 'FileObject'),
    subjects: [],
    legalBasis: CONSENT,
    retention: withParent,
    onSubjectErasure: noSubject('bytes follow their FileObject row (erased with it)'),
    onTenantPurge: tenantHook('files.owned'),
    edges: [],
    enforcement: CASCADE,
    holdAware: dataClass === 'legal_record' || dataClass === 'tenant_record' || dataClass.startsWith('user_content'),
    ...extra,
  };
}

