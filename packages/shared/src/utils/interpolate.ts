// ============================================================
// Рендер ПОЛЬЗОВАТЕЛЬСКИХ шаблонов «{{placeholder}}».
//
// Тексты ПРОДУКТА сюда больше не ходят: уведомления и хроника переехали на ICU
// (`@superapp/i18n`), потому что шаблон в коде — это один язык навсегда. Здесь
// остаётся ровно один законный случай: шаблон, который написал ЧЕЛОВЕК (шаг
// «Процессов», письмо-рассылка). Его нельзя переводить — он и есть контент, — и
// синтаксис `{{…}}` для него привычнее, чем ICU.
// ============================================================

/**
 * Подставляет `{{key}}` из `vars`. Правила:
 *  - отсутствующий / null / undefined ключ → пустая строка (клиент не видит `{{...}}`);
 *  - объект / массив → пустая строка (НИКОГДА не «[object Object]» в UI);
 *  - строка / число / boolean → String(value).
 * Ключи с точками ищутся плоско (vars['a.b']) — вложенный доступ не поддерживается.
 */
export function interpolateTemplate(
  template: string,
  vars: Record<string, unknown>,
): string {
  return template.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (_, key: string) => {
    const value = vars[key];
    if (value === undefined || value === null) return '';
    if (typeof value === 'object') return '';
    return String(value);
  });
}
