import type { AudienceKind } from '../constants/audiences';

/** Адресат: вид + id (у относительных видов и `user` id может быть якорем `$initiator`/`$subject`/`$self`) */
export interface AudienceRef {
  type: AudienceKind;
  id: string;
}

/**
 * Контекст разворота. Якоря подставляются отсюда; `workspaceId` скоупит всё:
 * чужой отдел разворачивается в пусто, человек вне команды — в пусто.
 */
export interface AudienceContext {
  workspaceId: string | null;
  /** `$initiator` — кто запустил (автор заявки, инициатор процесса) */
  initiatorId?: string | null;
  /** `$subject` — сторона документа (работник в приказе) */
  subjectId?: string | null;
  /** `$self` — текущий пользователь */
  selfId?: string | null;
  /** Объект, в контексте которого считается вертикаль (иначе — основное место) */
  branchId?: string | null;
}

/**
 * ЗАМОРОЖЕННАЯ подпись адресата — форма, в которой адресат ложится в ВЕЧНУЮ запись
 * (payload хроники и уведомления, снимок шага согласования).
 *
 * Готовая фраза в вечной записи застывает в языке того, кто нажал кнопку: «Отдел
 * «Продажи»», записанное по-русски, английский читатель получит по-русски и через
 * год. Поэтому в записи лежит СТРУКТУРА, а слово собирается при чтении
 * (`renderAudienceLabel` из `@superapp/i18n`, render-at-read — docs/i18n.md):
 *
 *   - `key` — КЛЮЧ каталога формы подписи («Отдел «{name}»», «Руководитель {who}»);
 *     слово продукта, переводится в языке ЗРИТЕЛЯ;
 *   - `name` — ДАННЫЕ: имя отдела/должности/объекта/Группы/человека СНИМКОМ на момент
 *     записи (справочник переименуют, а история должна остаться читаемой);
 *   - `kind` + `id` — сам адресат: фолбэк подписи, будущая ссылка-чип, отладка.
 *     `id` может быть якорем (`$initiator`) — слово якоря тоже собирается при чтении.
 */
export interface AudienceLabelSnapshot {
  kind: AudienceKind;
  id: string;
  /** Ключ каталога формы подписи; null — подпись целиком в `name` (человек) */
  key: string | null;
  /** Имя сущности снимком; null — у подписи нет данных (вся команда, якорь) */
  name: string | null;
}

/** Часть снимка, которую даёт РЕЗОЛВЕР вида (владелец данных): ключ формы + имя */
export type AudienceLabelPart = Pick<AudienceLabelSnapshot, 'key' | 'name'>;

/** Подписанный адресат (для витрин: «Отдел «Продажи»», «Руководитель инициатора») */
export interface AudienceLabelDto {
  type: AudienceKind;
  id: string;
  label: string;
}
