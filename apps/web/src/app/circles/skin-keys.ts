// Ключ каталога для имени ВСТРОЕННОГО скина.
//
// `DEFAULT_SKIN` — обычный объект `CardSkinRender`, тот же тип, что у купленных
// скинов, и его `name` рисуется там же, где имена платных. Имена платных —
// ДАННЫЕ (их задаёт автор скина), а имя встроенного — слово интерфейса: его
// нельзя оставить литералом, иначе базовая карточка навсегда осталась бы
// «Базовым» на любом языке.
//
// Поэтому в `name` встроенного скина лежит КЛЮЧ, а рендер подменяет его
// переводом через `skinName()`. Отдельный файл нужен, чтобы `card-skin.ts`
// (чистый модуль без React) не тянул за собой хуки.

export const DEFAULT_SKIN_NAME_KEY = 'circles.skin.default';

/** Имя скина для показа: встроенный — из каталога, купленный — как есть. */
export function skinName(name: string, t: (key: string) => string): string {
  return name === DEFAULT_SKIN_NAME_KEY ? t('skin.default') : name;
}
