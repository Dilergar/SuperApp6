// ============================================================
// Тон ноды канваса — матовая четвёрка (заливка, бордер, штрих, база).
//
// Тот же приём, что у чипов кита (DESIGN.md §1), но в виде объекта: React Flow
// кладёт цвет ноды миникарты и обводку рёбер в inline-style / атрибуты SVG, где
// класс кита не работает. Значения — ТОЛЬКО var(...): хардкод цвета запрещён.
// Карта «тон → переменные» одна на приложение (`toneVars`), здесь лишь проекция.
// ============================================================
import { toneVars, type Tone } from '@/components/ui';

export interface CanvasTone {
  /** Заливка матовой подложки. */
  bg: string;
  /** Бордер подложки. */
  border: string;
  /** Цвет штриха иконки и текста на подложке. */
  fg: string;
  /** Насыщенная база — точка на миникарте, кольцо статуса. */
  base: string;
}

/** Матовая четвёрка системного тона (для нод, миникарты, рёбер). */
export function canvasTone(tone: Tone): CanvasTone {
  const v = toneVars(tone) as Record<string, string>;
  return {
    bg: v['--tone-bg'],
    border: v['--tone-border'],
    fg: v['--tone-fg'],
    base: v['--tone-base'],
  };
}
