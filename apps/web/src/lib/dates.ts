// ============================================================
// Даты в интерфейсе — ОДНО описание формата.
// Календарная дата с сервера всегда едет как `YYYY-MM-DD` (`@db.Date`), а человеку
// в КЗ показывается как `ДД.ММ.ГГГГ`. Идиома `iso.split('-').reverse().join('.')`
// успела разойтись по семи файлам (Контрагенты, Документы, Сроки КЭДО, карточка
// сотрудника, «замещает до»), и каждая копия по-своему решала, что делать с пустым
// значением. Здесь один формат и один фолбэк.
//
// ЯЗЫК ЗДЕСЬ НИ ПРИ ЧЁМ, и это не упрощение: числовая дата принадлежит РЕГИОНУ,
// а не языку (модель Apple/Salesforce). Человек, выбравший English, в Казахстане
// по-прежнему видит `03.09.2026`, а не `9/3/2026`. Поэтому функции остаются
// чистыми — им не нужен ни хук, ни контекст. Там, где в дате есть СЛОВА (месяц
// прописью, «Сегодня»), формат зависит от языка — и это уже `lib/format.ts`.
// ============================================================
import { formatDate } from '@superapp/i18n/format';
import { SOURCE_LOCALE } from '@superapp/shared';

// Локаль-заглушка: у числовых стилей ('short'/'dayMonth') порядок частей и
// разделитель берутся из профиля региона, поэтому результат от языка не зависит.
const NUMERIC = { locale: SOURCE_LOCALE } as const;

/** `2026-09-03` → `03.09.2026`; пусто → пусто */
export const dmy = (iso: string | null | undefined): string =>
  iso ? formatDate(iso.slice(0, 10), NUMERIC, 'short') : '';

/** То же, но пустое значение — прочерком (таблицы и карточки, где строка обязана быть) */
export const dmyOrDash = (iso: string | null | undefined): string => dmy(iso) || '—';

/** `2026-09-03` → `03.09` (компактно: рёбра схемы, короткие периоды) */
export const dm = (iso: string | null | undefined): string =>
  iso ? formatDate(iso.slice(0, 10), NUMERIC, 'dayMonth') : '';
