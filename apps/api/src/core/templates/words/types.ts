/**
 * Числительные ОДНОГО языка — словарь и грамматика «прописью».
 *
 * Число разбирается на триады (по три разряда справа налево) один раз и для
 * всех языков; собирает из них фразу сам язык: у русского внутри триады есть
 * род и три формы разряда, у казахского и английского — свои правила.
 */
export interface NumberWords {
  /** Сколько триад язык умеет назвать (тысячи, миллионы, … — потолок «прописи») */
  maxScale: number;
  /** Ноль отдельным словом: пустая фраза в документе недопустима */
  zero: string;
  /** Приставка отрицательного числа */
  minus: string;
  /**
   * Триады от МЛАДШЕЙ к старшей (`triads[0]` — сотни-десятки-единицы), как их
   * отдаёт разбор числа. Порядок слов принадлежит языку.
   */
  toWords(triads: number[]): string;
  /** Денежная фраза: сумма прописью + тиыны цифрами (валюта РК) */
  money(amountWords: string, frac2: string): string;
}
