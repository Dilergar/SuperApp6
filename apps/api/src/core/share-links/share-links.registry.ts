import { Injectable, Logger } from '@nestjs/common';

/**
 * Контекст объекта, на который выдаётся ссылка. Возвращает резолвер потребителя —
 * движок сам таблиц Диска, документов и будущих счетов не знает.
 */
export interface ShareRefContext {
  /** Владелец объекта: на него ложится ответственность за раздачу наружу */
  ownerType: 'user' | 'workspace';
  ownerId: string;
  /** Организация — для «Журнала организации»; у личных объектов null */
  workspaceId: string | null;
  /** Название объекта для управляющего интерфейса и записи в хронику */
  title: string;
  /**
   * Значок объекта (ключ реестра иконок кита). Вместе с названием он снимается в
   * СНИМОК на строке ссылки, чтобы раздел «Ссылки наружу» рисовался без обращения к
   * потребителю за каждой строкой.
   */
  icon?: string;
}

/** То, что движок знает о ссылке, показывая её гостю */
export interface ShareLinkGuestContext {
  linkId: string;
  refType: string;
  refId: string;
  /**
   * Владелец разрешил гостю скачивать оригиналы. Решение принимает ПОТРЕБИТЕЛЬ: у
   * каждого свой смысл «показать, но не отдать» (у файла — уменьшенная копия, у
   * документа — только спрятанная кнопка, потому что просмотрщик PDF всё равно свой).
   */
  allowDownload: boolean;
  /** Пер-refType опции ссылки (v1 пусто; сюда ЭДО положит свои настройки подписания) */
  settings: Record<string, unknown>;
  /**
   * ЛИЧНОСТЬ гостя, если ссылка её требовала (подтверждённый номер). Нужна
   * потребителям с персональным состоянием: подпись показывает вернувшемуся
   * подписанту ЕГО акт («вы подписали», «вы отказались: причина»), а не «перейти
   * к подписанию». Диск и документы поле игнорируют. `null` — ссылка анонимная
   * либо вид резолвится до подтверждения личности.
   */
  guest: { id: string; name: string; phone: string } | null;
}

/**
 * Резолвер потребителя движка гостевых ссылок. Регистрируется в onModuleInit
 * своего модуля (паттерн FilesRefRegistry): движок не импортирует ни один
 * функциональный модуль, направление знания — только от потребителя к движку.
 *
 * Новый сервис получает «поделиться наружу» одной такой регистрацией — гостевая
 * страница, срок, отзыв, счётчик открытий и журнал визитов уже есть.
 */
export interface ShareLinkProvider {
  /**
   * Право УПРАВЛЯТЬ ссылками на этот объект (создать, отозвать, посмотреть журнал).
   * Планка — своя у каждого потребителя: у Диска это «управляющий узла», у
   * документов — владелец.
   *
   * Два разных отказа, и путать их нельзя:
   *  - `null` → движок отвечает 404. Это ответ ПОСТОРОННЕМУ: существование чужого
   *    объекта не подтверждаем даже фактом «нет прав».
   *  - брошенный `ForbiddenException` → 403 с настоящей причиной. Это ответ тому, кто
   *    объект ВИДИТ, но не управляет им. Ему 404 «Объект не найден» — прямая ложь: он
   *    смотрит на этот объект в своём же списке (на диске организации роль «правит»
   *    есть у каждого сотрудника, и весь блок ссылок наружу отвечал им «не найдено»).
   */
  authorizeManage(userId: string, refId: string): Promise<ShareRefContext | null>;

  /**
   * Что увидит гость. Зовётся на КАЖДЫЙ показ страницы, а не единожды при выдаче
   * ссылки: объект мог уехать в корзину или измениться. null → 410 «объект
   * недоступен» (движок не отзывает ссылку — из корзины объект ещё вернётся).
   */
  resolveGuestView(link: ShareLinkGuestContext): Promise<unknown | null>;

  /**
   * Подпись объекта: страница «Мои ссылки» (батч) и уведомление «ссылку открыли».
   * `href` — куда вести владельца из уведомления (карточка заявки/объекта);
   * без него уведомление ведёт в общий раздел «Ссылки наружу».
   */
  describeRef?(refId: string): Promise<{ title: string; icon?: string; href?: string } | null>;

  /**
   * ДЕЙСТВИЯ гостя над объектом — то, ради чего слот и ждал первого потребителя
   * (им стал core/sign: внешний контрагент подписывает документ по ссылке).
   *
   * Ключ действия свободен и принадлежит ПОТРЕБИТЕЛЮ: движок ссылок не знает ни
   * подписи, ни оплаты, ни опросов — он лишь подтверждает, что по ту сторону
   * действующая ссылка и (если она того требует) названный человек, и передаёт
   * управление. Право на само действие проверяет потребитель.
   *
   * Гость приходит без аккаунта, поэтому в обработчик едет `GuestActionContext`,
   * а не userId: личность — это запись `ShareLinkGuest` (подтверждённый номер),
   * и заводить под неё второго «пользователя» платформа не будет.
   */
  actions?: Record<string, (ctx: GuestActionContext) => Promise<unknown>>;

  /**
   * Ограничения на САМУ ссылку для этого типа объекта.
   *
   * Появилось ради подписи: «умрёт после N открытий» на подписной ссылке
   * запирает подписанта снаружи — он открыл документ, дочитал до конца, вернулся
   * за ключом ЭЦП, а ссылка уже исчерпана, и связаться с отправителем ему нечем.
   * Для просмотра эта настройка осмысленна, для действия — вредна.
   */
  constraints?: {
    /** Запретить лимит открытий (подписные ссылки) */
    forbidMaxOpens?: boolean;
    /**
     * Требовать подтверждение личности ВСЕГДА, не оставляя это на выбор создателю.
     *
     * Нужно подписи: по такой ссылке не просто смотрят файл — по ней ставят подпись,
     * и до появления этого флага ссылку можно было выдать анонимной. Тогда документ,
     * ушедший на подпись контрагенту, читал любой, кому переслали адрес, а движок
     * подписи полагался на то, что личность включили вручную.
     */
    requireIdentity?: boolean;
  };
}

/** Что видит обработчик действия гостя */
export interface GuestActionContext {
  refType: string;
  refId: string;
  /** Строка ссылки: срок, настройки, тумблеры — потребителю они бывают нужны */
  link: { id: string; allowDownload: boolean; settings: Record<string, unknown> };
  /**
   * Личность гостя, если ссылка её требовала. `null` — ссылка анонимная, и
   * потребитель сам решает, годится ли это для его действия (для подписи — нет).
   */
  guest: { id: string; name: string; phone: string } | null;
  body: unknown;
  ip: string | null;
  userAgent: string | null;
}

@Injectable()
export class ShareLinksRegistry {
  private readonly logger = new Logger(ShareLinksRegistry.name);
  private readonly entries = new Map<string, ShareLinkProvider>();

  register(refType: string, provider: ShareLinkProvider): void {
    if (this.entries.has(refType)) {
      this.logger.warn(`provider for "${refType}" already registered — overwriting`);
    }
    this.entries.set(refType, provider);
  }

  get(refType: string): ShareLinkProvider | undefined {
    return this.entries.get(refType);
  }

  /** Зарегистрированные типы — для дев-диагностики и сообщений об ошибке */
  types(): string[] {
    return [...this.entries.keys()];
  }
}
