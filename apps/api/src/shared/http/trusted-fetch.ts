/**
 * ДВЕРЬ №2 наружу: адрес пришёл ИЗ .env, то есть его выбрал ОПЕРАТОР при установке,
 * а не пользователь запросом. Так ходят сидекары платформы — редактор документов
 * (`DOCS_EDITOR_URL`), Gotenberg (`GOTENBERG_URL`), верификатор ЭЦП (`NCANODE_URL`),
 * STT (`VOICE_STT_URL`), мост подписи (`SMARTBRIDGE_URL`), SMS-шлюз (`KIT_URL`).
 *
 * SSRF-щита здесь НЕТ, и это НАМЕРЕННО, а не упущение: адреса сидекаров приватны по
 * построению (`http://localhost:9980`, `http://host.docker.internal:3001`), и щит
 * двери №1 отверг бы их первым же условием — самохостовая сборка перестала бы
 * работать целиком. Щит защищает от «пользователь подсунул адрес внутренней сети»;
 * здесь подсунуть нечего — строку задаёт тот, кто и так владеет сервером.
 *
 * Что дверь даёт взамен:
 *  1. Вызов ЗАЯВЛЕН доверенным. Голый `fetch` запрещён линтером, поэтому автор новой
 *     интеграции обязан выбрать дверь ОСОЗНАННО и назвать, откуда у него адрес. Раньше
 *     этот выбор делался молчанием — так `process-ai-client` и уехал мимо щита (SSRF,
 *     security-ревью 2026-07-25).
 *  2. Таймаут ОБЯЗАТЕЛЕН по сигнатуре. Забыть его больше нельзя: висящий запрос к
 *     упавшему сидекару держит слот джоба до конца аренды и выглядит как «очередь встала».
 *  3. Одна точка, куда лягут будущие ретраи, метрики и логи исходящих.
 *
 * Поведение — ровно как у голого `fetch` с `AbortSignal.timeout`: ничего не
 * переписываем на лету, чтобы переезд существующих клиентов был без сюрпризов.
 */

/** Разрешённые источники доверенного адреса — для читаемости места вызова. */
export type TrustedOrigin =
  /** Строка целиком приехала из переменной окружения (сидекар, внешний шлюз). */
  | 'env'
  /** Наш же API по `API_PUBLIC_URL` — самообращение (лого в шапку бланка). */
  | 'self';

export interface TrustedFetchOptions {
  /** Максимум ожидания, мс. Обязателен: без него зависший сидекар держит вызывающего. */
  timeoutMs: number;
  /** Откуда взялся адрес. Не влияет на поведение — документирует место вызова. */
  origin: TrustedOrigin;
}

/**
 * Запрос к доверенному адресу (см. шапку файла). Для адресов из пользовательских
 * данных используйте `safeFetch` — у него SSRF-щит.
 */
export async function trustedFetch(
  url: string,
  init: RequestInit,
  opts: TrustedFetchOptions,
): Promise<Response> {
  // Свой сигнал вызывающего (отмена) уважаем: складываем с таймаутом двери.
  const signal = init.signal
    ? AbortSignal.any([init.signal, AbortSignal.timeout(opts.timeoutMs)])
    : AbortSignal.timeout(opts.timeoutMs);
  // eslint-disable-next-line no-restricted-globals -- внутренности двери: тот самый один законный fetch
  return fetch(url, { ...init, signal });
}
