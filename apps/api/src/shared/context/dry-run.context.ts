import { AsyncLocalStorage } from 'node:async_hooks';

// ============================================================
// «Идёт предпросмотр» — сквозной признак для эффектов ВНЕ базы.
//
// Предпросмотр команды кабинета (`POST /platform/commands/:key/preview`) исполняет
// `execute` в транзакции, которая ВСЕГДА откатывается: строки в БД исчезают сами.
// А всё, что живёт вне транзакции — INCR эпохи в Redis, событие шины, письмо, вызов
// наружу, — не откатывается ничем. Один «предпросмотр публикации версии плана»
// сбрасывал бы кэш тарифов всей платформы, а «предпросмотр смены подписки» слал бы
// членам организации сокет «тариф изменился», хотя ничего не менялось.
//
// Поэтому исполнитель предпросмотра оборачивает вызов в `DryRun.run(...)`, а КАЖДЫЙ
// эффект вне БД спрашивает `DryRun.active()` перед тем, как случиться. ALS переживает
// await'ы внутри обёртки — отдельный флаг протаскивать через сигнатуры не нужно.
// ============================================================

const als = new AsyncLocalStorage<true>();

export const DryRun = {
  /** Выполнить внутри предпросмотра: эффекты вне БД внутри — молчат. */
  run<T>(fn: () => Promise<T>): Promise<T> {
    return als.run(true, fn);
  },
  /** Идёт ли предпросмотр в текущем контексте выполнения. */
  active(): boolean {
    return als.getStore() === true;
  },
};
