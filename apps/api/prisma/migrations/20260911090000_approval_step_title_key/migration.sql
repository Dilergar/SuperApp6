-- Автозаголовок шага согласования: заголовок собрала ПЛАТФОРМА, а не человек.
--
-- Маршруты из библиотеки кадровых бланков называют шаги сами («Согласовать:
-- Заявление на отпуск»). Записанный фразой, заголовок застывал в языке источника,
-- и казахоязычный сотрудник читал в стопке «Approve: Leave application», хотя весь
-- остальной интерфейс у него на казахском.
--
-- Теперь рядом с заголовком лежат ключ каталога и его параметры: `title` остаётся
-- снимком (поиск, фолбэк для старых заявок), а человек читает заголовок на своём
-- языке. Заголовок, набранный человеком, ключа не имеет и не трогается никогда.
ALTER TABLE "approval_steps" ADD COLUMN "title_key" TEXT;
ALTER TABLE "approval_steps" ADD COLUMN "title_params" JSONB;
