-- «Один файл — одна карточка документа».
--
-- Правило было объявлено в коде (`createUploadedDocument` проверял занятость
-- чтением), но держалось только на нём: два параллельных `POST /documents/upload`
-- с одним fileId проходили обе проверки до обеих вставок и заводили две карточки
-- на один файл. Дальше они делили правку и подписание — заморозка одной закрывала
-- редактор другой, а `resolveSubject` обеих отдавал на подпись один и тот же PDF.
--
-- NULL'ы в Postgres различны, поэтому карточки без файла (черновик, пока джоб
-- собирает бланк) уникуму не мешают.
CREATE UNIQUE INDEX "org_documents_file_id_key" ON "org_documents"("file_id");
