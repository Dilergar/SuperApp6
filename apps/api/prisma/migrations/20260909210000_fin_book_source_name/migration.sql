-- Имя книги финансов — АВТОимя платформы, а не данные владельца: переименования
-- книги в продукте нет вовсе, а показывается имя чужому человеку (список «книги,
-- которыми со мной делятся»). Дефолт колонки был русским, то есть один язык для
-- всех навсегда; теперь он в языке ИСТОЧНИКА, а зрителю имя перерисовывает
-- `FinancesService.bookName` (та же механика, что у системных папок Диска).
ALTER TABLE "fin_books" ALTER COLUMN "name" SET DEFAULT 'My finances';

-- Строки, заведённые прежним дефолтом. Точное сравнение, а не LIKE: тронуть можно
-- только то, что поставила БД сама, — всё остальное было бы чужим выбором.
UPDATE "fin_books" SET "name" = 'My finances' WHERE "name" = 'Мои финансы';
