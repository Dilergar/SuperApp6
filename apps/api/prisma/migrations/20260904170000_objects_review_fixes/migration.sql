-- РЕВЬЮ СЕРВИСА «ОБЪЕКТЫ»: две ловушки уровня БД.
-- ============================================================

-- 1) Имя объекта было уникально на ВСЮ организацию — наследие плоского справочника
--    филиалов. В дереве это ломает нормальное именование: «Этаж 1» бывает и в здании А,
--    и в здании Б, а сеть кофеен держит по «Залу» на каждой точке.
--    Уникальность переносим на пару «родитель + имя» и только среди ЖИВЫХ: архивный
--    объект имя больше не держит.
--    ⚠️ Дропаем по ФАКТИЧЕСКОМУ имени (Postgres режет имена до 63 символов — здесь
--    короче, но правило одно на все миграции проекта).
ALTER TABLE "staff_branches" DROP CONSTRAINT IF EXISTS "staff_branches_workspace_id_name_key";
DROP INDEX IF EXISTS "staff_branches_workspace_id_name_key";

-- COALESCE, а не голый parent_id: в уникальном индексе NULL не равен NULL, и два
-- корневых объекта с одинаковым именем проскочили бы мимо ограничения.
CREATE UNIQUE INDEX "staff_branches_parent_name_key"
  ON "staff_branches" ("workspace_id", COALESCE("parent_id", ''), "name")
  WHERE "archived_at" IS NULL;

-- 2) Идемпотентность пропускной системы. `source_ref` — id события устройства;
--    вебхуки доставляют at-least-once, и каждый ретрай заводил НОВУЮ строку факта
--    (а внеплановую запись до сих пор нечем было удалить). Уникум страхует гонку
--    двух доставок, прикладная проверка в recordAttendanceSystem — обычный повтор.
CREATE UNIQUE INDEX "shift_attendance_source_ref_key"
  ON "shift_attendance" ("workspace_id", "source_ref")
  WHERE "source_ref" IS NOT NULL;
