-- «Одна живая заявка на один шаг ведущего маршрута».
--
-- Prisma партиальные уникальные индексы не выражает, поэтому руками (тот же приём,
-- что у call_sessions и document_sessions). Уникальность строится на ПАРЕ ВЕДУЩЕГО
-- (origin_type + origin_ref = «инстанс:шаг»), а НЕ на предмете (ref_type + ref_id):
-- на одном документе законно живут два параллельных согласования — например,
-- подпись директора и ознакомление отдела идут одновременно, и уник по предмету
-- запретил бы нарисовать такой маршрут вовсе.
--
-- Что он закрывает: движок Процессов исполняет шаги at-least-once, и повторный
-- толчок ноды «Решение человека» после уже закоммиченной заявки завёл бы вторую
-- на тот же шаг — человек получил бы один документ дважды, а маршрут ждал бы
-- ответа по обеим. Прикладной обход этой гонки (посмотреть-и-создать) её не
-- закрывает; индекс закрывает.
CREATE UNIQUE INDEX IF NOT EXISTS "approval_requests_one_active_per_origin"
  ON "approval_requests" ("origin_type", "origin_ref")
  WHERE "status" = 'pending' AND "origin_type" IS NOT NULL;
