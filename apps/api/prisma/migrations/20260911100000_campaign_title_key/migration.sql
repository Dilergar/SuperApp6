-- Автозаголовок кампании ознакомления: заголовок собрала ПЛАТФОРМА.
--
-- Когда менеджер не задал своё название, кампания называлась «<документ> No. 123» —
-- собранной фразой в языке источника. Слово «No.» застывало английским у всех,
-- хотя в русском и казахском на его месте «№».
--
-- Теперь рядом с заголовком лежат ключ каталога и параметры: `title` остаётся
-- снимком (поиск и фолбэк старых кампаний), а читателю заголовок собирается на его
-- языке. Название, набранное человеком, ключа не имеет и не трогается.
ALTER TABLE "doc_campaigns" ADD COLUMN "title_key" TEXT;
ALTER TABLE "doc_campaigns" ADD COLUMN "title_params" JSONB;
