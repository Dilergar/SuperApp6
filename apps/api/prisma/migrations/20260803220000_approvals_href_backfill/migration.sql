-- Починка уже РАЗОСЛАННЫХ уведомлений движка согласований.
--
-- `actionUrl` записывается в строку уведомления навсегда, поэтому исправление
-- кода само по себе не лечит те письма, что уже лежат в ленте: человек нажимает
-- на них и попадает в 404. Адрес карточки заявки собирался строкой в двух местах
-- API и вёл на `/workspaces/:id/documents/approvals/:id` — страницы с таким путём
-- в вебе нет вовсе; теперь он один (`approvalHref` в shared) и равен
-- `/approvals/:id`.
--
-- Переписываем ТОЛЬКО согласовательные адреса обеих старых форм, забирая
-- последний сегмент (идентификатор заявки). Идемпотентно: уже починенные строки
-- под условие не попадают.
UPDATE "notifications"
SET "action_url" = '/approvals/' || regexp_replace("action_url", '^.*/approvals/', '')
WHERE "action_url" LIKE '/workspaces/%/documents/approvals/%'
   OR "action_url" LIKE '/tasks/approvals/%';
