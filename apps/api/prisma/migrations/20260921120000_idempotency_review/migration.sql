-- ---------- 1. «Входящий ящик»: аренда обработки ----------
-- Приёмник, чья обработка не помещается в одну транзакцию (внутри сетевые вызовы),
-- отмечал событие ДО обработки и снимал отметку только на пойманной ошибке. Процесс,
-- умерший посреди работы (деплой, OOM), отметку не снимал — и редоставка источника
-- гасилась как дубль: событие терялось навсегда. Теперь строка бывает «в работе»
-- (`done_at IS NULL`) под арендой по `received_at`; истекла — редоставка забирает её.
--
-- DEFAULT CURRENT_TIMESTAMP — для строк, вставленных МИМО `begin` (старый инстанс во
-- время выката, Prisma `create`): они сразу «обработаны», как и было раньше. Уже
-- существующие строки получают то же значение — все они обработаны.
ALTER TABLE "idempotency_inbox" ADD COLUMN "done_at" TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP;

-- ---------- 2. idem.keys: поиск поддержки по сырому ключу ----------
-- Команда кабинета `idempotency.key.lookup` ищет по ОДНОМУ `key_hash` (скоуп у каждого
-- свой и оператору неизвестен). С первичным ключом (scope_hash, key_hash) это был
-- последовательный проход всех 16 партиций. Порядок колонок меняется на
-- (key_hash, scope_hash): поиск по паре равенств работает так же, поиск по префиксу
-- `key_hash` получает индекс — и всё это без второго индекса на горячей таблице.
-- `ON CONFLICT (scope_hash, key_hash)` выводится по НАБОРУ колонок, порядок ему не важен.
--
-- Оба оператора идут в одной транзакции миграции под ACCESS EXCLUSIVE: между DROP и
-- ADD никто не пишет. Таблица хранит не больше недели заявок — перестройка короткая.
ALTER TABLE idem.keys DROP CONSTRAINT "idem_keys_pkey";
ALTER TABLE idem.keys ADD CONSTRAINT "idem_keys_pkey" PRIMARY KEY ("key_hash", "scope_hash");
