-- Диктофон: автоимя записи больше НЕ хранится.
--
-- «Запись 05.09.2026 21:07» — это не имя, которое ввёл человек, а снимок на языке,
-- который был у него в момент создания. Сменив язык, он навсегда оставался бы со
-- старым именем. Пустой `title` = имя собирается ПРИ ЧТЕНИИ в языке зрителя
-- (render-at-read, docs/i18n.md); непустой — имя, введённое руками.
ALTER TABLE "voice_recordings" ALTER COLUMN "title" DROP NOT NULL;

-- Момент, который называет автоимя. У записи звонка это НАЧАЛО разговора: `created_at`
-- у неё — это когда запись доехала из егресса, то есть уже после конца звонка.
ALTER TABLE "voice_recordings" ADD COLUMN "title_at" TIMESTAMP(3);

-- Бэкфилл. Сначала сохраняем момент звонка (иначе он потеряется вместе с именем):
-- берём его у движка звонков, пока имя ещё позволяет отличить автоимя от ручного.
UPDATE "voice_recordings" v
SET "title_at" = c."started_at"
FROM "call_recordings" c
WHERE v."call_recording_id" = c."id"
  AND v."title" ~ '^Звонок [0-9]{2}\.[0-9]{2}\.[0-9]{4} [0-9]{2}:[0-9]{2}$';

-- И только теперь зануляем автоимена прошлой эпохи. Шаблон строгий: имя, которое
-- человек написал сам («Планёрка по движку»), под него не попадает.
UPDATE "voice_recordings"
SET "title" = NULL
WHERE "title" ~ '^(Запись|Звонок) [0-9]{2}\.[0-9]{2}\.[0-9]{4} [0-9]{2}:[0-9]{2}$';
